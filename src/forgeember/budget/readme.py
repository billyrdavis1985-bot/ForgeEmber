"""Render the README "Budget & Trace" block and the cumulative-spend SVG from a snapshot.

Everything here is a pure function of ``traces/budget-snapshot.json``. Output has no clock
reads or random ordering, so CI can regenerate it and compare byte for byte.
"""

from __future__ import annotations

from decimal import Decimal
from typing import Any

from forgeember.budget.pricing import NANO_PER_USD, fmt_usd

START_MARKER = "<!-- budget:start -->"
END_MARKER = "<!-- budget:end -->"
CHART_PATH = "docs/assets/budget-chart.svg"


class MarkerError(ValueError):
    pass


def _usd(nusd: int | None, places: int | None = None) -> str:
    return "n/a" if nusd is None else fmt_usd(int(nusd), places=places)


def _pct(num: int, den: int) -> str:
    if den == 0:
        return "n/a"
    return f"{(Decimal(num) * 100 / den).quantize(Decimal('0.1'))}%"


def _cache_rate(snap: dict[str, Any]) -> str:
    if snap["input_tokens"] == 0:
        return "n/a"
    pct = _pct(snap["cached_input_tokens"], snap["input_tokens"])
    return f"{pct} of {snap['input_tokens']:,} input tokens"


def render_block(snap: dict[str, Any]) -> str:
    per_item = snap["cost_per_item_nusd"]
    per_item_nusd = None if per_item is None else int(Decimal(per_item).to_integral_value())
    per_1000 = None if per_item is None else int((Decimal(per_item) * 1000).to_integral_value())
    rec = snap["last_reconciliation"]
    if rec is None:
        rec_text = "not yet recorded"
    else:
        verdict = "ledger >= Meta" if rec["difference_nusd"] >= 0 else "**LEDGER UNDERCOUNTS**"
        rec_text = (
            f"{rec['ts'][:10]}: Meta {_usd(rec['meta_total_nusd'])}, ledger "
            f"{_usd(rec['ledger_total_nusd'])} ({verdict})"
        )
    lines = [
        START_MARKER,
        "<!-- Generated by scripts/render_budget_readme.py from traces/budget-snapshot.json. "
        "Do not edit by hand: CI fails if this block drifts from the ledger. -->",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Total spent | **{_usd(snap['spent_nusd'])}** of the {_usd(snap['grant_nusd'])} limit |",
        f"| Hard cap enforced in code | {_usd(snap['cap_nusd'])} "
        f"(headroom **{_usd(snap['headroom_to_cap_nusd'])}**) |",
        f"| Ember calls recorded | {snap['calls_settled']:,} "
        f"({snap['overruns']} over their reservation) |",
        f"| Items screened | {snap['items']:,} |",
        f"| Cost per item | {_usd(per_item_nusd, 6)} |",
        f"| Cost per 1,000 items | {_usd(per_1000, 4)} |",
        f"| Projected monthly cost, small business (3,000 emails) | "
        f"{_usd(snap['projected_monthly_nusd_3000_items'], 4)} |",
        f"| Prompt-cache hit rate | {_cache_rate(snap)} |",
        f"| Saved by prompt caching | {_usd(snap['cache_savings_nusd'])} |",
        f"| Reasoning share of output tokens | "
        f"{_pct(snap['reasoning_tokens'], snap['output_tokens'])} |",
        f"| Last reconciliation with Meta's Usage page | {rec_text} |",
        "",
        "| Stage | Limit | Spent | Open | Remaining |",
        "|---|---:|---:|---:|---:|",
    ]
    for st in snap["stages"]:
        remaining = st["limit_nusd"] - st["spent_nusd"] - st["open_nusd"]
        lines.append(
            f"| {st['stage']} | {_usd(st['limit_nusd'])} | {_usd(st['spent_nusd'])} | "
            f"{_usd(st['open_nusd'])} | {_usd(remaining)} |"
        )
    for title, key in (("Input kind", "by_input_kind_nusd"), ("Agent role", "by_agent_role_nusd")):
        if snap[key]:
            lines += ["", f"| {title} | Spent |", "|---|---:|"]
            lines += [f"| {k} | {_usd(v)} |" for k, v in snap[key].items()]
    as_of = snap["last_ts"] or "no calls yet"
    lines += [
        "",
        f"![Cumulative Ember spend against the {_usd(snap['cap_nusd'])} hard cap]({CHART_PATH})",
        "",
        f"Ledger as of: {as_of}. Full per-call trace: `traces/calls.jsonl`.",
        END_MARKER,
    ]
    return "\n".join(lines)


def replace_block(readme: str, block: str) -> str:
    start, end = readme.find(START_MARKER), readme.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise MarkerError("README must contain budget:start and budget:end markers in order")
    if readme.count(START_MARKER) != 1 or readme.count(END_MARKER) != 1:
        raise MarkerError("README must contain exactly one budget block")
    return readme[:start] + block + readme[end + len(END_MARKER) :]


def extract_block(readme: str) -> str:
    start, end = readme.find(START_MARKER), readme.find(END_MARKER)
    if start == -1 or end == -1 or end < start:
        raise MarkerError("README budget markers missing")
    return readme[start : end + len(END_MARKER)]


def render_svg(snap: dict[str, Any]) -> str:
    """Cumulative spend (by call number) against the hard cap and the event's limit."""
    width, height = 640, 260
    left, right, top, bottom = 64, 24, 28, 44
    plot_w, plot_h = width - left - right, height - top - bottom
    grant = snap["grant_nusd"]
    cap = snap["cap_nusd"]
    points = snap["cumulative"]
    n = len(points)

    def y(nusd: int) -> float:
        return top + plot_h * (1 - nusd / grant)

    def x(i: int) -> float:
        return left + (plot_w * i / n if n else 0)

    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="t">',
        '<title id="t">Cumulative Muse Ember spend against the hard cap</title>',
        f'<rect width="{width}" height="{height}" fill="#ffffff"/>',
    ]
    for usd in range(0, grant // NANO_PER_USD + 1, 2):
        yy = y(usd * NANO_PER_USD)
        parts.append(
            f'<line x1="{left}" y1="{yy:.1f}" x2="{left + plot_w}" y2="{yy:.1f}" '
            'stroke="#e5e7eb" stroke-width="1"/>'
        )
        parts.append(
            f'<text x="{left - 8}" y="{yy + 4:.1f}" font-family="sans-serif" font-size="11" '
            f'fill="#4b5563" text-anchor="end">${usd}</text>'
        )
    parts.append(
        f'<line x1="{left}" y1="{y(grant):.1f}" x2="{left + plot_w}" y2="{y(grant):.1f}" '
        'stroke="#6b7280" stroke-width="1.5"/>'
    )
    parts.append(
        f'<text x="{left + plot_w}" y="{y(grant) - 6:.1f}" font-family="sans-serif" '
        f'font-size="11" fill="#374151" text-anchor="end">limit {_usd(grant)} '
        "(over = disqualified)</text>"
    )
    parts.append(
        f'<line x1="{left}" y1="{y(cap):.1f}" x2="{left + plot_w}" y2="{y(cap):.1f}" '
        'stroke="#b91c1c" stroke-width="2" stroke-dasharray="6 4"/>'
    )
    parts.append(
        f'<text x="{left + plot_w}" y="{y(cap) + 14:.1f}" font-family="sans-serif" '
        f'font-size="11" fill="#b91c1c" text-anchor="end">hard cap {_usd(cap)} '
        "(enforced in code)</text>"
    )
    coords = [f"{x(0):.1f},{y(0):.1f}"] + [
        f"{x(i + 1):.1f},{y(v):.1f}" for i, (_, v) in enumerate(points)
    ]
    if n == 0:
        coords.append(f"{left + plot_w:.1f},{y(0):.1f}")
    parts.append(
        f'<polyline points="{" ".join(coords)}" fill="none" stroke="#1d4ed8" stroke-width="2.5"/>'
    )
    spent_label = f"spent {_usd(snap['spent_nusd'])} over {n:,} calls"
    parts.append(
        f'<text x="{left + 6}" y="{y(0) - 8:.1f}" font-family="sans-serif" font-size="12" '
        f'fill="#1d4ed8">{spent_label}</text>'
    )
    parts.append(
        f'<text x="{left + plot_w / 2:.1f}" y="{height - 12}" font-family="sans-serif" '
        'font-size="11" fill="#4b5563" text-anchor="middle">Ember calls, in settlement order</text>'
    )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"
