"""Generate fictional fraud and normal-business fixtures with known answers.

    uv run python scripts/gen_fixtures.py            # writes fixtures/
    uv run python scripts/gen_fixtures.py --no-images --no-audio

Outputs fixtures/manifest.json (expected category, risk, held actions and invoice fields per
item), fixtures/baselines.json (fictional organization and vendor records), invoice PDFs, a
scanned-invoice PNG, .eml emails and voicemails (espeak-ng and ffmpeg needed for the audio).
Everything is invented and generated by code, so we own it.
"""

from __future__ import annotations

import argparse

from forgeember.attackgen import generate_attacks
from forgeember.config import Paths, find_root
from forgeember.fixturegen import generate


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-images", action="store_true", help="skip the Pillow-rendered scan")
    parser.add_argument("--no-audio", action="store_true", help="skip the voicemail recordings")
    args = parser.parse_args(argv)
    root = Paths(root=find_root()).root
    for path in generate(root / "fixtures", images=not args.no_images, audio=not args.no_audio):
        print(f"wrote {path.relative_to(root)}")
    if not args.no_images:  # the attack suite needs Pillow too (a photo, a page image)
        attacks = generate_attacks(root / "fixtures" / "attacks", audio=not args.no_audio)
        for path in attacks:
            print(f"wrote {path.relative_to(root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
